const needleSystem = `You write one search question that a specific passage answers.

The question must:
- be answerable from this passage alone,
- name the specific things the passage is about, as a real user would,
- avoid quoting long phrases verbatim — a question that copies a sentence tests
  string matching rather than retrieval.

Ask about the passage's actual content, not about the document's structure.

Reply with a JSON object only: {"question": "..."}`

// evalRetrieval measures recall@k over the whole corpus.
//
// It exists because the hand-written answer cases cannot measure this. Those
// cases were authored by reading the corpus, which makes them a test of eight
// chosen questions; this generates one question per chunk and asks whether that
// chunk comes back, so every chunk gets probed and the questions are not chosen
// for their answerability.
//
// The generator sees ONE chunk and knows nothing about the index, the tiers, or
// what retrieval will do — so it cannot flatter the system by construction, the
// way an author who has read everything can.
func evalRetrieval(args []string) error {
	fs := flag.NewFlagSet("eval-retrieval", flag.ExitOnError)
	indexPath := fs.String("index", defaultIndexPath, "index to probe")
	topK := fs.Int("k", 5, "retrieve this many; recall is measured at this depth")
	limit := fs.Int("limit", 0, "probe at most this many chunks (0 = all)")
	rerank := fs.Bool("rerank", false, "rescore the shortlist with a cross-encoder before measuring (needs RERANK_BASE_URL)")
	rerankLLM := fs.Bool("rerank-llm", false, "rescore with the chat model instead — measured worse than no reranking")
	hyde := fs.Bool("hyde", false, "embed a hypothetical answer alongside each probe (one call per chunk)")
	save := fs.String("save", "", "write this run's per-chunk ranks here, for a later --baseline")
	baseline := fs.String("baseline", "", "compare against a run saved with --save")
	label := fs.String("label", "", "name this run in comparison output (e.g. \"bge-reranker-base\")")
	verbose := fs.Bool("v", false, "show every probe, not just misses")
	questionsPath := fs.String("questions", "", "write the generated questions here, as answer-eval cases")
	jobs := fs.Int("jobs", defaultJobs, "chunks to probe concurrently")
	if err := fs.Parse(args); err != nil {
		return err
	}

	st, err := buildStack(stackOptions{IndexPath: *indexPath, Rerank: *rerank, RerankLLM: *rerankLLM})
	if err != nil {
		return err
	}
	chunks, _ := st.store.Entries()
	if len(chunks) == 0 {
		return fmt.Errorf("index %s is empty", *indexPath)
	}
	if *limit > 0 && *limit < len(chunks) {
		chunks = chunks[:*limit]
	}

	// Questions are generated by the utility model and cached on chunk content,
	// so re-running the probe is free and the question set stays fixed — a
	// benchmark that silently rewrites itself measures nothing over time.
	util, utilName, _ := utilityLLM(st.client)
	cache := index.NewCache(defaultCacheDir)
	semantic := tiers.NewSemantic(st.store)

	// Expansion runs on the utility model, the same one that writes the probe
	// questions — which is fine here and worth naming: the generator sees only
	// one chunk and the expander sees only the question, so neither knows what
	// the right answer is.
	var expander agent.Expander
	if *hyde {
		expander = &agent.HyDE{LLM: util}
	}

	fmt.Printf("=== retrieval recall: %d chunks, k=%d, rerank=%s, hyde=%v ===\n\n",
		len(chunks), *topK, rerankLabel(*rerank, *rerankLLM), *hyde)

	ctx := context.Background()

	// One probe per chunk, concurrently, reported in chunk order.
	type probe struct {
		question string
		rank     int // -1 = not retrieved
		fresh    bool
		skipped  bool
		err      error
	}
	probes := mapIndexed(len(chunks), *jobs, "probing", func(i int) probe {
		c := chunks[i]
		q, fresh, err := needleQuestion(ctx, util, cache, utilName, c)
		if err != nil || strings.TrimSpace(q) == "" {
			// No well-formed question for this chunk, so it goes unmeasured.
			// Counted and reported: dropping chunks quietly and printing a
			// recall over what remains is how a benchmark flatters itself.
			return probe{skipped: true, err: err}
		}
		query := core.Query{Text: q, TopK: *topK}
		if expander != nil {
			// An expander failure retrieves the query as written rather than
			// failing the probe, matching what the loop does.
			query.Expanded, _ = expander.Expand(ctx, q)
		}
		got, err := semantic.Retrieve(ctx, query)
		if err != nil {
			return probe{question: q, fresh: fresh, err: err}
		}
		p := probe{question: q, rank: -1, fresh: fresh}
		for j, r := range got {
			if r.SourceID == c.ID {
				p.rank = j
				break
			}
		}
		return p
	})

	var probed, hitAt1, hitAtK, generated, cached, skipped int
	ranks := make(map[string]int, len(chunks))
	texts := make(map[string]string, len(chunks))
	var misses []string
	var cases []answerCase
	for i, p := range probes {
		c := chunks[i]
		if p.skipped {
			skipped++
			continue
		}
		if p.err != nil {
			return p.err
		}
		ranks[c.ID] = p.rank
		texts[c.ID] = chunkDigest(c.Embedded())
		if p.fresh {
			generated++
		} else {
			cached++
		}
		probed++
		switch {
		case p.rank == 0:
			hitAt1++
			hitAtK++
		case p.rank > 0:
			hitAtK++
		default:
			misses = append(misses, fmt.Sprintf("%s — %s", c.ID, truncate(p.question, 68)))
		}
		if *verbose {
			fmt.Printf("  rank %2d  %-28s %s\n", p.rank, c.ID, truncate(p.question, 56))
		}
		cases = append(cases, answerCase{
			Question:      p.question,
			ExpectSources: []string{c.DocID},
			Note:          "generated from " + c.ID,
		})
	}

	if len(misses) > 0 && !*verbose {
		fmt.Printf("missed (chunk not in top %d for its own question):\n", *topK)
		sort.Strings(misses)
		for _, m := range misses {
			fmt.Printf("  %s\n", m)
		}
		fmt.Println()
	}
	if probed == 0 {
		return fmt.Errorf("no chunks could be probed")
	}
	fmt.Printf("coverage:  %d/%d chunks probed", probed, len(chunks))
	if skipped > 0 {
		fmt.Printf(" (%d skipped — no question that identifies the chunk rather than referring to it)", skipped)
	}
	fmt.Printf("\nquestions: %d generated, %d from cache\n", generated, cached)
	fmt.Printf("recall@1:  %d/%d (%.0f%%)\n", hitAt1, probed, 100*float64(hitAt1)/float64(probed))
	fmt.Printf("recall@%d:  %d/%d (%.0f%%)\n", *topK, hitAtK, probed, 100*float64(hitAtK)/float64(probed))

	run := retrievalRun{Label: *label, TopK: *topK, Ranks: ranks, Texts: texts}
	if run.Label == "" {
		run.Label = fmt.Sprintf("rerank=%s hyde=%v k=%d", rerankLabel(*rerank, *rerankLLM), *hyde, *topK)
	}
	// Compare before saving, so `--save x --baseline x` diffs against the
	// previous run rather than against what this one just wrote.
	if *baseline != "" {
		base, err := loadRun(*baseline)
		if err != nil {
			return err
		}
		compareRuns(base, run)
	}
	if *save != "" {
		if err := saveRun(*save, run); err != nil {
			return err
		}
		fmt.Printf("\nsaved %d per-chunk ranks to %s\n", len(ranks), *save)
	}

	if *questionsPath != "" {
		if err := writeCases(*questionsPath, cases); err != nil {
			return err
		}
		fmt.Printf("\nwrote %d generated cases to %s (add must_include to grade answers)\n", len(cases), *questionsPath)
	}
	return nil
}

// metaPhrases mark a question that refers to its source rather than naming its
// subject. Such a question cannot identify one chunk — "what configurations are
// mentioned in the passage?" fits every chunk about configuration — so scoring
// retrieval against it measures the generator, not the index. Observed once in
// 70 on a real corpus, and it was the only miss.
var metaPhrases = []string{
	"the passage", "this passage", "the text", "this text",
	"the document", "this document", "the excerpt", "this excerpt",
	"the chunk", "this chunk", "the section", "mentioned in the",
	"described above", "listed above", "shown above",
	"this file", "this markdown", "name of this", "this readme",
}

func isMetaQuestion(q string) bool {
	lower := strings.ToLower(q)
	for _, p := range metaPhrases {
		if strings.Contains(lower, p) {
			return true
		}
	}
	return false
}

// needleQuestion returns a question answerable from c, and whether it was
// freshly generated.
func needleQuestion(ctx context.Context, l llm.LLM, cache *index.Cache, tag string, c core.Chunk) (string, bool, error) {
	key := index.Key("needle|"+tag, c.DocID, c.Text)
	if q, ok := cache.Get(key); ok && strings.TrimSpace(q) != "" && !isMetaQuestion(q) {
		return q, false, nil
	}
	msgs := []llm.Message{
		llm.System(needleSystem),
		llm.User(fmt.Sprintf("<passage>\n%s\n</passage>", strings.TrimSpace(c.Text))),
	}
	// Retry a meta-phrased question once; the instruction not to write one is in
	// the prompt, so a second sample usually complies rather than needing a
	// stronger instruction.
	var q string
	for attempt := range 2 {
		var out struct {
			Question string `json:"question"`
		}
		if err := l.ChatJSON(ctx, msgs, &out); err != nil {
			return "", false, err
		}
		q = strings.TrimSpace(out.Question)
		if q != "" && !isMetaQuestion(q) {
			break
		}
		if attempt == 1 {
			// Still meta after a retry: skip rather than score against it.
			return "", false, nil
		}
	}
	if q != "" {
		_ = cache.Put(key, q)
	}
	return q, true, nil
}

func writeCases(path string, cases []answerCase) error {
	var b strings.Builder
	b.WriteString("[\n")
	for i, c := range cases {
		fmt.Fprintf(&b, "  {\n    %q: %q,\n    %q: [],\n    %q: [%q],\n    %q: %q\n  }",
			"question", c.Question, "must_include", "expect_sources", c.ExpectSources[0], "note", c.Note)
		if i < len(cases)-1 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString("]\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}
